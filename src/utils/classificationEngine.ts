/**
 * AUTOMATIC CONVERTER & CALCULATOR CLASSIFICATION ENGINE
 * 
 * Enforces Chapter 25 architecture rules for UnitsConvertors.com:
 * 1. Unit Converters:
 *    - Fixed mathematical conversion ratio
 *    - 1 input, 1 output
 *    - No assumptions, no external variables
 *    - SI / NIST / ISO standardized exact mathematical relationship
 * 
 * 2. Engineering Calculators:
 *    - Requires external variables (distance, area, beam angle, temperature, pressure, humidity, material properties, etc.)
 *    - Multi-variable physical models & engineering equations
 *    - Explicit governing equations and mandatory physical assumptions
 */

export type PageClassificationType = "unit-converter" | "engineering-calculator";

export interface ClassificationResult {
  type: PageClassificationType;
  category: string;
  isExactMath: boolean;
  requiresExternalVariables: boolean;
  hasAssumptions: boolean;
  indexingPolicy: "index, follow" | "noindex, follow";
  reason: string;
}

export interface ContentQualityMetrics {
  hasOriginalArticle?: boolean;
  hasFormula?: boolean;
  hasWorkedExamples?: boolean;
  hasReferenceTable?: boolean;
  hasFaqs?: boolean;
  faqCount?: number;
  hasPracticalApplications?: boolean;
  wordCount?: number;
}

